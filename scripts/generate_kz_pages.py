def format_price_kz(price: int) -> str:
    return f"{int(price):,}".replace(",", " ")


def get_livi_sku(pid: str) -> str:
    m = re.search(r"(\d+)", pid)
    num = m.group(1) if m else pid
    return f"LIVI-{int(num):02d}"


