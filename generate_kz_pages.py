    tr = KZ_TRANSLATIONS.get(pid, {})
    title_kz = tr.get("title") or p.get("title", "")
    desc_kz = tr.get("desc") or p.get("description", "")
    mats_ru = p.get("materials") or ["Натуральный жемчуг"]
    mats_kz = [MATERIAL_MAP_KZ.get(m, m) for m in mats_ru]

    # bundle options translation
    bundle_opts = p.get("bundle_options") or []
    kz_bundle_names = BUNDLE_OPTIONS_KZ.get(pid, [])
    bundle_opts_kz = []
    for idx, opt in enumerate(bundle_opts):
        opt_kz_name = kz_bundle_names[idx] if idx < len(kz_bundle_names) else opt["name"]
        bundle_opts_kz.append({
            "name": opt_kz_name,
            "name_ru": opt["name"],
            "price": opt["price"],
            "is_full": opt.get("is_full", False),
        })

    return {
        "id": pid,
        "sku": p.get("sku") or get_livi_sku(pid),
        "title": title_kz,
        "title_ru": p.get("title", ""),
        "description": desc_kz,
        "price": int(p.get("price") or 0),
        "category": p.get("category") or "Necklaces",
        "image": "/" + p["image"].lstrip("/"),
        "materials": mats_kz,
        "materials_ru": mats_ru,
        "specs": p.get("specs") or {},
        "search_keywords": p.get("search_keywords") or [],
        "bundle_options": bundle_opts_kz,
        "inStock": p.get("inStock", True),
    }


