function main() {
  Logger.log("==================================================================");
  Logger.log("💎 LIVI JEWELRY: СИНХРОНИЗАЦИЯ МАСТЕР-СПИСКА МИНУС-СЛОВ");
  Logger.log("   Кампании: Поиск (Search) + Google Shopping");
  Logger.log("==================================================================");

  // 1. Поиск или создание мастер-списка минус-слов
  var listIter = AdsApp.negativeKeywordLists().withCondition("Name = '" + CONFIG.LIST_NAME + "'").get();
  var masterList;

  if (listIter.hasNext()) {
    masterList = listIter.next();
    Logger.log("✓ Найден существующий мастер-список: " + CONFIG.LIST_NAME);
  } else {
    var builder = AdsApp.newNegativeKeywordListBuilder().withName(CONFIG.LIST_NAME).build();
    masterList = builder.getResult();
    Logger.log("✓ Создан новый мастер-список: " + CONFIG.LIST_NAME);
  }

  // 2. Считываем уже добавленные минус-слова в списке (защита от повторного добавления)
  var existingKeywords = {};
  var existingCount = 0;
  try {
    var nkIter = masterList.negativeKeywords().get();
    while (nkIter.hasNext()) {
      var nk = nkIter.next();
      var cleanText = nk.getText().toLowerCase().trim().replace(/^["\[]|["\]]$/g, "");
      existingKeywords[cleanText] = true;
      existingKeywords[nk.getText().toLowerCase().trim()] = true;
      existingCount++;
    }
    Logger.log("✓ В списке уже присутствует: " + existingCount + " минус-слов.");
  } catch (e) {
    Logger.log("[i] Примечание при чтении списка: " + e);
  }

  // 3. Добавление фразовых минус-слов
  var addedPhrases = 0;
  for (var i = 0; i < PHRASE_NEGATIVES.length; i++) {
    var pWord = PHRASE_NEGATIVES[i].toLowerCase().trim();
    if (!existingKeywords[pWord] && !existingKeywords['"' + pWord + '"']) {
      try {
        masterList.addNegativeKeyword('"' + pWord + '"');
        existingKeywords[pWord] = true;
        addedPhrases++;
      } catch (err) {
        // Пропускаем технические ошибки
      }
    }
  }
  Logger.log("✓ Добавлено новых фразовых минус-слов: " + addedPhrases);

  // 4. Добавление точных минус-слов
  var addedExacts = 0;
  for (var j = 0; j < EXACT_NEGATIVES.length; j++) {
    var eWord = EXACT_NEGATIVES[j].toLowerCase().trim().replace(/^\[|\]$/g, "");
    var formattedExact = "[" + eWord + "]";
    if (!existingKeywords[eWord] && !existingKeywords[formattedExact]) {
      try {
        masterList.addNegativeKeyword(formattedExact);
        existingKeywords[formattedExact] = true;
        addedExacts++;
      } catch (errEx) {
        // Пропускаем ошибки
      }
    }
  }
  Logger.log("✓ Добавлено новых точных минус-слов: " + addedExacts);

  // 5. Прикрепление мастер-списка ко всем Поисковым кампаниям (Search)
  var searchAttached = 0;
  if (CONFIG.APPLY_TO_SEARCH) {
    Logger.log("\n--- ПРИВЯЗКА К ПОИСКОВЫМ КАМПАНИЯМ (SEARCH) ---");
    var searchIter = AdsApp.campaigns().get();
    while (searchIter.hasNext()) {
      var sCamp = searchIter.next();
      var sName = sCamp.getName();
      try {
        sCamp.addNegativeKeywordList(masterList);
        searchAttached++;
        Logger.log("  [Search] ✓ Защищен: " + sName);
      } catch (errCamp) {
        Logger.log("  [Search] [i] " + sName + " (уже привязан или системный статус)");
      }
    }
  }

  // 6. Прикрепление мастер-списка ко всем Торговым кампаниям (Google Shopping)
  var shoppingAttached = 0;
  if (CONFIG.APPLY_TO_SHOPPING) {
    Logger.log("\n--- ПРИВЯЗКА К ТОРГОВЫМ КАМПАНИЯМ (SHOPPING) ---");
    try {
      var shopIter = AdsApp.shoppingCampaigns().get();
      while (shopIter.hasNext()) {
        var shopCamp = shopIter.next();
        var shopName = shopCamp.getName();
        try {
          shopCamp.addNegativeKeywordList(masterList);
          shoppingAttached++;
          Logger.log("  [Shopping] ✓ Защищен: " + shopName);
        } catch (errShop) {
          Logger.log("  [Shopping] [i] " + shopName + " (уже привязан или системный статус)");
        }
      }
    } catch (eShopIter) {
      Logger.log("  [Shopping] Ошибка итерации Shopping: " + eShopIter);
    }
  }

  Logger.log("\n==================================================================");
  Logger.log("🎉 ИТОГИ СИНХРОНИЗАЦИИ:");
  Logger.log("   • Всего слов в базе скрипта: " + (PHRASE_NEGATIVES.length + EXACT_NEGATIVES.length));
  Logger.log("   • Новых слов добавлено в мастер-список: " + (addedPhrases + addedExacts));
  Logger.log("   • Поисковых кампаний обработано: " + searchAttached);
  Logger.log("   • Shopping кампаний защищено: " + shoppingAttached);
  Logger.log("   • Статус: ВСЕ КАМПАНИИ ЗАЩИЩЕНЫ ОТ ИНФО-МУСОРА И ЗОДИАКОВ!");
  Logger.log("==================================================================");
}
