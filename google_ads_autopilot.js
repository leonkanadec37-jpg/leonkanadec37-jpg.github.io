function evaluateSearchTerm(term) {
  var lower = (term || "").toLowerCase().trim().replace(/^["\[]|["\]]$/g, "").trim();
  if (!lower) return { isJunk: false, isExactOnly: false, isSafe: false, reason: "Пустой запрос" };

  // 1. Бренд конкурента -> МГНОВЕННЫЙ БАН (Фразовое соответствие)
  for (var b = 0; b < COMPETITOR_BRANDS.length; b++) {
    if (COMPETITOR_BRANDS[b].test(lower)) {
      return { isJunk: true, isExactOnly: false, isSafe: false, reason: "Бренд-конкурент (" + COMPETITOR_BRANDS[b] + ")" };
    }
  }

  // 2. Одиночные широкие категории ("колье", "серьги", "бусы", "браслет", "ожерелье", "сотуар", "бижутерия") -> ТОЧНОЕ СООТВЕТСТВИЕ [X]
  if (isSingleWordCategoryTerm(lower)) {
    return { isJunk: true, isExactOnly: true, isSafe: false, reason: "Однословный общий запрос категории без камня [точное соответствие]" };
  }

  var hasSafeStone = isSafeStoneTerm(lower);
  var isLineJewelry = isLineJewelryTerm(lower);

  // 3. Проверка на стоп-паттерны с исключениями Livi Jewelry (RU + KZ + UZ)
  for (var j = 0; j < JUNK_PATTERNS.length; j++) {
    if (JUNK_PATTERNS[j].test(lower)) {
      var patStr = String(JUNK_PATTERNS[j]);

      // Исключение А (RU + KZ + UZ): Позолота (позолота / tilla suvi / oltin suvi / алтын жалатылған) + наш камень
      var isGoldPlatedRu = /позолот/i.test(lower) && !/(^|\s)золот/i.test(lower);
      var isGoldPlatedUz = /(tilla|oltin|тилла|олтин)\s*(suvi|qoplama|ранг|суви|қоплама)/i.test(lower);
      var isGoldPattern = patStr.indexOf("золот") !== -1 || patStr.indexOf("tilla") !== -1 || patStr.indexOf("тилла") !== -1 || patStr.indexOf("oltin") !== -1 || patStr.indexOf("олтин") !== -1;
      if (hasSafeStone && (isGoldPlatedRu || isGoldPlatedUz) && isGoldPattern) {
        continue;
      }

      // Исключение Б: Покупка нашего конкретного камня/жемчуга в подарок (кроме годовщин свадеб и "что дарить")
      var isWeddingAnniversary = /(агатов|бирюзов|лавандов|ситцев|деревянн|розов|серебрян|золот).*свадьб|на\s+[а-яё]+\s+свадьбу|что\s+дарить/i.test(lower);
      var isGiftPattern = patStr.indexOf("подар") !== -1 || patStr.indexOf("день рожден") !== -1 || patStr.indexOf("юбилей") !== -1 || patStr.indexOf("sovg") !== -1 || patStr.indexOf("совға") !== -1 || patStr.indexOf("tug") !== -1;
      if ((hasSafeStone || isLineJewelry) && isGiftPattern && !isWeddingAnniversary) {
        continue;
      }

      // Исключение В и Г (RU + UZ): Пусеты, серьги-гвоздики, кольца и узбекские uzuk/zirak
      // Если в запросе есть наш камень/жемчуг — разрешаем!
      // Если камня в запросе НЕТ — блокируем ТОЛЬКО В ТОЧНОМ СООТВЕТСТВИИ [X], чтобы не резать "marvarid zirak" и "кольцо с жемчугом"!
      var isRingOrStudPattern = (
        patStr === "/кольц/i" ||
        patStr === "/колечк/i" ||
        patStr === "/перстен/i" ||
        patStr === "/пусет/i" ||
        patStr === "/пуссет/i" ||
        patStr === "/гвоздик/i" ||
        patStr.indexOf("uzuk") !== -1 ||
        patStr === "/узук/i" ||
        patStr.indexOf("zirak") !== -1 ||
        patStr === "/зирак/i"
      );
      if (isRingOrStudPattern) {
        if (hasSafeStone || isLineJewelry) {
          continue;
        } else {
          return {
            isJunk: true,
            isExactOnly: true,
            isSafe: false,
            reason: "Общий запрос кольца/пусеты/uzuk/zirak без камня [точное соответствие]"
          };
        }
      }

      // Исключение Д: Кулоны, колье, сотуары и браслеты на леске / тросике
      if (isLineJewelry && (patStr.indexOf("леск") !== -1 || patStr.indexOf("тросик") !== -1)) {
        continue;
      }

      // Исключение Е: Готовые украшения (колье, браслет, серьги, чокер и т.д.) с бусиной/бусинами
      if (patStr.indexOf("бусин") !== -1) {
        var isDiyBeadsQuery = /бусин.*для|для.*бусин|для\s+сборк|для\s+рукодел|бусины\s+оптом/i.test(lower);
        if (isJewelryProductTerm(lower) && !isDiyBeadsQuery) {
          continue;
        }
      }

      return { isJunk: true, isExactOnly: false, isSafe: false, reason: "Стоп-паттерн (" + JUNK_PATTERNS[j] + ")" };
    }
  }

  // 4. Однословные камни, двухсловные инфо-запросы и многословные цены сырья БЕЗ изделия -> ТОЧНОЕ СООТВЕТСТВИЕ [X]
  if (isTwoWordStoneLookup(lower)) {
    return { isJunk: true, isExactOnly: true, isSafe: false, reason: "Инфо/сырьевой запрос без изделия [точное соответствие]" };
  }

  return {
    isJunk: false,
    isExactOnly: false,
    isSafe: hasSafeStone || isLineJewelry,
    reason: (hasSafeStone || isLineJewelry) ? "Целевой камень / изделие мастерской" : "Общий целевой запрос"
  };
}

function shouldUnblockNegative(term, mType) {
  var lower = (term || "").toLowerCase().trim().replace(/^["\[]|["\]]$/g, "").trim();
  if (!lower) return false;

  // Принудительно снимаем ошибочные фразовые блоки со слов:
  // "леска", "тросик", "казахский", "казахские", "национальные", "майкаинская", "картографическая", "морская", "свадьба", "цвет"
  var forcedUnblockWords = {
    "леска": true,
    "тросик": true,
    "казахский": true,
    "казахские": true,
    "национальные": true,
    "майкаинская": true,
    "картографическая": true,
    "морская": true,
    "свадьба": true,
    "цвет": true
  };
  if (forcedUnblockWords[lower]) {
    return true;
  }

  for (var i = 0; i < SEED_ROOT_NEGATIVES.length; i++) {
    if (SEED_ROOT_NEGATIVES[i].toLowerCase().trim() === lower) {
      return false;
    }
  }

  if (mType === "EXACT") {
    for (var e = 0; e < SEED_EXACT_NEGATIVES.length; e++) {
      if (SEED_EXACT_NEGATIVES[e].toLowerCase().trim() === lower) {
        return false;
      }
    }
  }

  // СТРОГО: Разблокируем ТОЛЬКО те фразы из минус-слов, которые:
  // 1) НЕ являются мусором (!evalRes.isJunk)
  // 2) И СТРОГО являются целевыми изделиями Livi (evalRes.isSafe === true)
  var evalRes = evaluateSearchTerm(lower);
  if (!evalRes.isJunk && evalRes.isSafe) {
    return true;
  }

  return false;
}

function shouldConvertPhraseToExact(term, mType) {
  if (mType === "EXACT") return false;
  var lower = (term || "").toLowerCase().trim().replace(/^["\[]|["\]]$/g, "").trim();
  if (!lower) return false;

  var evalRes = evaluateSearchTerm(lower);
  return evalRes.isJunk && evalRes.isExactOnly;
}

