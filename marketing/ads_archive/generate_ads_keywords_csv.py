def main():
    rows = []
    # Заголовок стандартного импорта Google Ads
    rows.append(["Campaign", "Ad Group", "Keyword", "Criterion Type", "Final URL"])

    total_keywords = 0
    for g in GROUPS_DATA:
        ad_group = g["ad_group"]
        url = g["url"]
        for kw in g["keywords"]:
            clean_kw = kw.strip().lower()
            # Добавляем Phrase
            rows.append([CAMPAIGN_NAME, ad_group, clean_kw, "Phrase", url])
            # Добавляем Exact
            rows.append([CAMPAIGN_NAME, ad_group, clean_kw, "Exact", url])
            total_keywords += 2

    # Сохраняем в 1_google_ads_keywords.csv с кодировкой utf-8-sig (Excel / Google Ads friendly)
    output_path = "1_google_ads_keywords.csv"
    with open(output_path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        writer.writerows(rows)

    print(f"Успешно сгенерировано {len(rows)-1} записей ({total_keywords} ключевых слов в Phrase/Exact) в {output_path}")

if __name__ == "__main__":
    main()
